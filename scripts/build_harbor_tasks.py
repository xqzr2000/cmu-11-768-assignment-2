def solve_sh(plot: str, note: str = "") -> str:
    header = "#!/bin/bash\n# Reference solution: writes plot.py, then runs it to make figure.png\n" \
             "# and plotted_values.json in /app.\n"
    if note:
        header = "#!/bin/bash\n# MUTANT: " + "\n# ".join(textwrap.wrap(note, 76)) + "\n"
    return (header + "set -euo pipefail\ncd /app\ncat > plot.py <<'PLOT_EOF'"
            + plot.rstrip() + "\nPLOT_EOF\npython plot.py\n")


def task_toml(task_id: str, spec: dict, text: str) -> str:
    text = text.replace('  "/app/plot.py",\n]', '  "/app/plot.py",\n  "/app/plotted_values.json",\n]')
    text = text.replace('description = "TODO: describe the task."',
                        f'description = "{spec["description"]}"')
    text = text.replace('name = "TODO: your name"', f'name = "{AUTHOR}"')
    text = text.replace('chart_family = "TODO"', f'chart_family = "{spec["chart_family"]}"')
    return "\n".join(line for line in text.splitlines() if "TODO" not in line) + "\n"


def main() -> None:
    for task_id, spec in TASKS.items():
        base = HARBOR / "tasks" / task_id
        assert base.is_dir(), f"run `uv run python -m workflow package` first ({base})"
        env = base / "environment"
        inputs = {name: sha(env / name) for name in spec["inputs"]}

        toml = base / "task.toml"
        toml.write_text(task_toml(task_id, spec, toml.read_text()))

        docker = env / "Dockerfile"
        lines = docker.read_text().splitlines()
        cut = next(i for i, line in enumerate(lines) if line.startswith("WORKDIR /app"))
        tail = [f"COPY {name} /app/{name}" for name in spec["inputs"]]
        head = [line for line in lines[:cut] if "TODO" not in line]
        docker.write_text("\n".join(head + ["WORKDIR /app"] + tail) + "\n")

        instruction = base / "instruction.md"
        seeded = instruction.read_text().split(REQUIRED_HEADING)[0].rstrip()
        reads = (f" It must read `{'`, `'.join(spec['inputs'])}` and compute the values "
                 "rather than hard-code results." if spec["inputs"] else "")
        prohibition = (f"Do not modify `{'`, `'.join(spec['inputs'])}`.\n\n" if spec["inputs"] else "")
        instruction.write_text(seeded + "\n\n" + REQUIRED_HEADING + "\n\n" + COMMON_OUTPUTS.format(
            reads=reads, schema=spec["schema"], prohibition=prohibition))

        (base / "solution" / "solve.sh").write_text(solve_sh(spec["plot"]))
        tests = base / "tests"
        for source in SHARED:
            shutil.copy2(source, tests / source.name)
        (tests / "test_state.py").write_text(
            TEST_HEADER.format(task_id=task_id, inputs=json.dumps(inputs)) + spec["tests"].lstrip("\n"))
        print(f"built {task_id}")

    for (task_id, name), (note, mutate) in MUTANTS.items():
        target = HARBOR / "tasks" / task_id / "mutants" / name
        target.mkdir(parents=True, exist_ok=True)
        plot = mutate(TASKS[task_id]["plot"])
        assert plot != TASKS[task_id]["plot"], f"mutant {name} changed nothing"
        (target / "solve.sh").write_text(solve_sh(plot, note))
        print(f"mutant {task_id}/{name}")


if __name__ == "__main__":
    main()
